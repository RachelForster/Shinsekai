"""Narrow dependencies consumed by conversation orchestration."""

from collections.abc import Callable
from typing import Any, Protocol


class ToolCatalog(Protocol):
    def get_definitions(self, groups: str | list[str] | None = None) -> list[dict]: ...
    def get_tool_group(self, name: str) -> str: ...
    def get_groups(self) -> list[str]: ...


class ToolRunner(Protocol):
    def is_in_cooldown(self, group: str) -> bool: ...
    def cooldown_message_for_tool(self, name: str) -> str | None: ...
    def execute(self, name: str, arguments_json: Any, *, risk_confirm: Callable[[str, str, str], bool] | None = None) -> Any: ...


class ChatHost(Protocol):
    def notify_tool_call(self, tool_name: str) -> None: ...
    def confirm_risky_tool(self, tool_name: str, risk: str, args_text: str) -> bool: ...
    def post_context_token_estimate(self, estimate: dict[str, int]) -> None: ...


class MessageJournal(Protocol):
    def append(self, message: dict[str, Any]) -> None: ...


class HistoryCompactor(Protocol):
    compact_threshold: float
    def count_tokens(self, messages: list[dict]) -> int: ...
    def count_text_tokens(self, text: str) -> int: ...
    def auto_compact_if_needed(self, messages: list[dict]) -> list[dict]: ...
    def trim_messages_to_budget(self, messages: list[dict], *, token_budget: int, recent_message_limit: int) -> list[dict]: ...
    def set_token_count(self, count: int) -> None: ...
