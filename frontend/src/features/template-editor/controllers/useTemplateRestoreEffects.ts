import { useEffect, type Dispatch, type MutableRefObject, type SetStateAction } from "react";

import type { TemplateSummary } from "../../../entities/template/repository";
import { TRANSPARENT_BACKGROUND_NAME } from "../../../shared/constants";
import { useI18n } from "../../../shared/i18n";
import { normalizePlayerOptions } from "../../../shared/playerCharacterOptions";
import type {
  AppConfig,
  Character,
  CharacterPromptMode,
  MediaSelectionMode,
  MemoryMode,
  TemplateLaunchSession,
} from "../../../shared/platform/types";
import { compatibleInitialSpritePath } from "../../chat-startup/initialSpriteSelection";
import { buildSystemSyncKey } from "../templateContext";
import { normalizeTemplateSummary, templateGenerationKey, templateVoiceLanguages } from "../templateFlow";
import { buildRestoredSessionSnapshot } from "./templateSessionRestore";

interface UseTemplateRestoreEffectsOptions {
  appConfig: AppConfig | undefined;
  backgroundOptions: string[];
  characterPromptMode: CharacterPromptMode | undefined;
  characters: Character[];
  conversationId?: string;
  createOnly: boolean;
  lastAutoGeneratedKeyRef: MutableRefObject<string>;
  launchSession: TemplateLaunchSession | null | undefined;
  maxDialogItems: number;
  maxSpeechChars: number;
  primaryCharacters: string[];
  restoredSessionBackgroundRef: MutableRefObject<string | null>;
  selected: TemplateSummary | undefined;
  selectedBackground: string;
  selectedCharacters: string[];
  sessionDraftActive: boolean;
  sessionFetched: boolean;
  sessionRestored: boolean;
  setAllowPlayerDialogue: Dispatch<SetStateAction<boolean>>;
  setAutoOutfitSwitch: Dispatch<SetStateAction<boolean>>;
  setCharacterPromptMode: Dispatch<SetStateAction<CharacterPromptMode | undefined>>;
  setDraft: Dispatch<SetStateAction<TemplateSummary>>;
  setHistoryPath: Dispatch<SetStateAction<string>>;
  setInitSpritePath: Dispatch<SetStateAction<string>>;
  setInitialOutfits: Dispatch<SetStateAction<Record<string, string>>>;
  setManualBaseKey: Dispatch<SetStateAction<string>>;
  setMaxDialogItems: Dispatch<SetStateAction<number>>;
  setMaxSpeechChars: Dispatch<SetStateAction<number>>;
  setMediaSelectionMode: Dispatch<SetStateAction<MediaSelectionMode>>;
  setMemoryMode: Dispatch<SetStateAction<MemoryMode>>;
  setNameError: Dispatch<SetStateAction<string>>;
  setPlayerCharacter: Dispatch<SetStateAction<string>>;
  setPrimaryCharacters: Dispatch<SetStateAction<string[]>>;
  setReadPlayerSpeech: Dispatch<SetStateAction<boolean>>;
  setRoomId: Dispatch<SetStateAction<string>>;
  setSelectedBackground: Dispatch<SetStateAction<string>>;
  setSelectedCharacters: Dispatch<SetStateAction<string[]>>;
  setSelectedEffects: Dispatch<SetStateAction<string[]>>;
  setSelectedId: Dispatch<SetStateAction<string>>;
  setSessionDraftActive: Dispatch<SetStateAction<boolean>>;
  setSessionRestored: Dispatch<SetStateAction<boolean>>;
  setShowInitialSprite: Dispatch<SetStateAction<boolean>>;
  setSystemManuallyEdited: Dispatch<SetStateAction<boolean>>;
  setUseCg: Dispatch<SetStateAction<boolean>>;
  setUseChoice: Dispatch<SetStateAction<boolean>>;
  setUseCot: Dispatch<SetStateAction<boolean>>;
  setUseEffectPrompt: Dispatch<SetStateAction<boolean>>;
  setUseNarration: Dispatch<SetStateAction<boolean>>;
  setUseStat: Dispatch<SetStateAction<boolean>>;
  setUseTranslation: Dispatch<SetStateAction<boolean>>;
  setVoiceLanguage: Dispatch<SetStateAction<string>>;
  suppressNextAutoGenerateRef: MutableRefObject<boolean>;
  templates: TemplateSummary[];
  templatesPending: boolean;
  useCg: boolean;
  useChoice: boolean;
  useCot: boolean;
  useEffectPrompt: boolean;
  useNarration: boolean;
  useStat: boolean;
  useTranslation: boolean;
  voiceLanguage: string;
}

export function useTemplateRestoreEffects({
  appConfig,
  backgroundOptions,
  characterPromptMode,
  characters,
  conversationId,
  createOnly,
  lastAutoGeneratedKeyRef,
  launchSession,
  maxDialogItems,
  maxSpeechChars,
  primaryCharacters,
  restoredSessionBackgroundRef,
  selected,
  selectedBackground,
  selectedCharacters,
  sessionDraftActive,
  sessionFetched,
  sessionRestored,
  setAllowPlayerDialogue,
  setAutoOutfitSwitch,
  setCharacterPromptMode,
  setDraft,
  setHistoryPath,
  setInitSpritePath,
  setInitialOutfits,
  setManualBaseKey,
  setMaxDialogItems,
  setMaxSpeechChars,
  setMediaSelectionMode,
  setMemoryMode,
  setNameError,
  setPlayerCharacter,
  setPrimaryCharacters,
  setReadPlayerSpeech,
  setRoomId,
  setSelectedBackground,
  setSelectedCharacters,
  setSelectedEffects,
  setSelectedId,
  setSessionDraftActive,
  setSessionRestored,
  setShowInitialSprite,
  setSystemManuallyEdited,
  setUseCg,
  setUseChoice,
  setUseCot,
  setUseEffectPrompt,
  setUseNarration,
  setUseStat,
  setUseTranslation,
  setVoiceLanguage,
  suppressNextAutoGenerateRef,
  templates,
  templatesPending,
  useCg,
  useChoice,
  useCot,
  useEffectPrompt,
  useNarration,
  useStat,
  useTranslation,
  voiceLanguage,
}: UseTemplateRestoreEffectsOptions) {
  const { t } = useI18n();

  useEffect(() => {
    if (selected && !sessionDraftActive) {
      setSelectedId(selected.id);
      const normalized = normalizeTemplateSummary(structuredClone(selected));
      const nextMediaMode = createOnly ? "indexed" : (selected.mediaSelectionMode ?? "indexed");
      const savedPlayer = normalizePlayerOptions(selected);
      const charKey = templateGenerationKey({
        characters: selectedCharacters,
        characterPromptMode,
        primaryCharacters,
        mediaSelectionMode: nextMediaMode,
        playerCharacter: selectedCharacters.includes(savedPlayer.playerCharacter) ? savedPlayer.playerCharacter : "",
        readPlayerSpeech: savedPlayer.readPlayerSpeech,
        allowPlayerDialogue: savedPlayer.allowPlayerDialogue,
      });
      lastAutoGeneratedKeyRef.current = buildSystemSyncKey({
        characterKey: charKey,
        backgroundName: selectedBackground,
        voiceLanguage,
        useCg,
        useEffect: useEffectPrompt,
        useTranslation,
        useCot,
        useChoice,
        useNarration,
        useStat,
        maxSpeechChars,
        maxDialogItems,
      });
      setDraft(normalized);
      setMediaSelectionMode(nextMediaMode);
      setPlayerCharacter(savedPlayer.playerCharacter);
      setReadPlayerSpeech(Boolean(savedPlayer.playerCharacter && savedPlayer.readPlayerSpeech));
      setAllowPlayerDialogue(savedPlayer.allowPlayerDialogue);
      setSystemManuallyEdited(false);
      setManualBaseKey("");
      setNameError("");
    }
  }, [createOnly, selected, sessionDraftActive]);

  useEffect(() => {
    if (!sessionFetched || sessionRestored) {
      return;
    }
    if (!conversationId && launchSession?.templateFileDropdown && templatesPending) {
      return;
    }
    if (!launchSession) {
      setSessionRestored(true);
      return;
    }
    const restored = buildRestoredSessionSnapshot({
      createOnly,
      defaultName: t("template.defaultName"),
      launchSession,
      templates,
    });
    restoredSessionBackgroundRef.current = restored.restoredSessionBackground;
    lastAutoGeneratedKeyRef.current = restored.lastAutoGeneratedKey;
    setSystemManuallyEdited(restored.systemManuallyEdited);
    setManualBaseKey(restored.systemManuallyEdited ? restored.lastAutoGeneratedKey : "");
    setSessionDraftActive(true);
    setSelectedCharacters(restored.selectedCharacters);
    setPlayerCharacter(restored.playerCharacter);
    setReadPlayerSpeech(restored.readPlayerSpeech);
    setAllowPlayerDialogue(restored.allowPlayerDialogue);
    setCharacterPromptMode(restored.characterPromptMode);
    setPrimaryCharacters(restored.primaryCharacters);
    setMediaSelectionMode(restored.mediaSelectionMode);
    setSelectedBackground(restored.selectedBackground);
    setSelectedEffects(restored.selectedEffects);
    setVoiceLanguage(restored.voiceLanguage);
    setUseEffectPrompt(restored.useEffectPrompt);
    setUseTranslation(restored.useTranslation);
    setUseCg(restored.useCg);
    setUseCot(restored.useCot);
    setUseChoice(restored.useChoice);
    setUseNarration(restored.useNarration);
    setUseStat(restored.useStat);
    setMaxSpeechChars(restored.maxSpeechChars);
    setMaxDialogItems(restored.maxDialogItems);
    setInitSpritePath(restored.initSpritePath);
    setShowInitialSprite(restored.showInitialSprite);
    setMemoryMode(restored.memoryMode);
    setAutoOutfitSwitch(restored.autoOutfitSwitch);
    if (restored.initialOutfits) {
      setInitialOutfits(restored.initialOutfits);
    }
    setHistoryPath(restored.historyPath);
    setRoomId(restored.roomId);
    setSelectedId(restored.matchingTemplateId);
    setDraft(restored.draft);
    setSessionRestored(true);
  }, [conversationId, createOnly, launchSession, sessionFetched, sessionRestored, t, templates, templatesPending]);

  useEffect(() => {
    if (!backgroundOptions.includes(selectedBackground)) {
      setSelectedBackground(TRANSPARENT_BACKGROUND_NAME);
    }
  }, [backgroundOptions, selectedBackground, setSelectedBackground]);

  useEffect(() => {
    if (!sessionRestored || launchSession) {
      return;
    }
    const configuredLanguage = String(appConfig?.system_config.voice_language || "")
      .trim()
      .toLowerCase();
    const nextLanguage = templateVoiceLanguages.some((option) => option.value === configuredLanguage)
      ? configuredLanguage
      : "ja";
    if (!configuredLanguage || nextLanguage === voiceLanguage) {
      return;
    }
    suppressNextAutoGenerateRef.current = true;
    setVoiceLanguage(nextLanguage);
  }, [appConfig, launchSession, sessionRestored, setVoiceLanguage, suppressNextAutoGenerateRef, voiceLanguage]);

  useEffect(() => {
    if (!sessionRestored) {
      return;
    }
    setInitSpritePath((current) => compatibleInitialSpritePath({ characters, path: current, selectedCharacters }));
  }, [characters, selectedCharacters, sessionRestored, setInitSpritePath]);
}
