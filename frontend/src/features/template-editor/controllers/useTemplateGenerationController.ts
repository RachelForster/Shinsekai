import { useCallback, useEffect, useLayoutEffect, useRef } from "react";
import { useMutation, useQueryClient } from "@tanstack/react-query";

import {
  generateTemplate,
  saveUserPromptPresets,
  userPromptPresetsQueryKey,
  type UserPromptPresetLibrary,
} from "../../../entities/template/repository";
import { useI18n } from "../../../shared/i18n";
import { platformErrorCode } from "../../../shared/platform/errors";
import { useToast } from "../../../shared/ui";
import { compatibleInitialSpritePath } from "../../chat-startup/initialSpriteSelection";
import { buildSystemSyncKey } from "../templateContext";
import type { SystemPromptCommit, SystemPromptRulesDraft } from "../SystemPromptDialog";
import type { UserPromptCommit } from "../UserPromptPresetsDialog";
import { buildTemplateGenerateInput, normalizeTemplateSummary, templateGenerationKey } from "../templateFlow";
import { composeScenarioWithPresets, toAppliedPresets } from "../userPromptPresets";
import type { TemplateSessionState } from "./useTemplateSessionState";

export function useTemplateGenerationController(state: TemplateSessionState) {
  const queryClient = useQueryClient();
  const { showToast } = useToast();
  const { t } = useI18n();

  const generationInput = (
    nextBaseScenario = state.scenarioForSelectedCharacters(),
    overrides?: Partial<SystemPromptRulesDraft>,
  ) => {
    const nextScenario = composeScenarioWithPresets(nextBaseScenario, state.resolvedSelectedPresets);
    const effectiveMode = overrides?.mediaSelectionMode ?? state.mediaSelectionMode;
    const effectiveOptions = {
      useCg: state.useCg,
      useChoice: overrides?.useChoice ?? state.useChoice,
      useCot: overrides?.useCot ?? state.useCot,
      useEffect: overrides?.useEffectPrompt ?? state.useEffectPrompt,
      useNarration: overrides?.useNarration ?? state.useNarration,
      useStat: overrides?.useStat ?? state.useStat,
      useTranslation: overrides?.useTranslation ?? state.useTranslation,
    };
    const effectiveRuntime = {
      ...state.runtimeOptionsState,
      maxDialogItems: overrides?.maxDialogItems ?? state.maxDialogItems,
      maxSpeechChars: overrides?.maxSpeechChars ?? state.maxSpeechChars,
    };
    return buildTemplateGenerateInput({
      backgroundName: state.selectedBackground,
      characterPromptMode: state.characterPromptMode ?? "full",
      draft: { ...state.draft, scenario: nextScenario },
      effectNames: state.selectedEffects,
      mediaSelectionMode: effectiveMode,
      options: effectiveOptions,
      outputFormat: overrides?.outputFormat ?? state.outputFormat,
      runtime: effectiveRuntime,
      primaryCharacters: state.characterPromptMode === "compact" ? state.primaryCharacters : state.selectedCharacters,
      ...state.playerOptions,
      selectedCharacters: state.selectedCharacters,
    });
  };
  const latestGenerationInput = useRef(generationInput);
  useLayoutEffect(() => {
    latestGenerationInput.current = generationInput;
  });

  const applyResolvedCharactersFromGeneration = (resolvedCharacters: string[]) => {
    const resolvedCharactersKey = resolvedCharacters.join("\n");
    if (resolvedCharactersKey === state.selectedCharactersKey) {
      return;
    }
    state.suppressNextAutoGenerateRef.current = true;
    const resolvedPrimary = state.primaryCharacters.filter((name) => resolvedCharacters.includes(name));
    const nextCharKey = templateGenerationKey({
      characters: resolvedCharacters,
      characterPromptMode: state.characterPromptMode ?? "full",
      primaryCharacters: resolvedPrimary,
      mediaSelectionMode: state.mediaSelectionMode,
      ...state.playerOptions,
      playerCharacter: resolvedCharacters.includes(state.playerCharacter) ? state.playerCharacter : "",
    });
    state.lastAutoGeneratedKeyRef.current = buildSystemSyncKey({
      characterKey: nextCharKey,
      backgroundName: state.selectedBackground,
      voiceLanguage: state.voiceLanguage,
      useCg: state.useCg,
      useEffect: state.useEffectPrompt,
      useTranslation: state.useTranslation,
      useCot: state.useCot,
      useChoice: state.useChoice,
      useNarration: state.useNarration,
      useStat: state.useStat,
      maxSpeechChars: state.maxSpeechChars,
      maxDialogItems: state.maxDialogItems,
      outputFormat: state.outputFormat,
    });
    state.setPrimaryCharacters(resolvedPrimary);
    state.setSelectedCharacters(resolvedCharacters);
    state.setInitSpritePath((path) =>
      compatibleInitialSpritePath({
        characters: state.characters,
        path,
        preserveUnknown: false,
        selectedCharacters: resolvedCharacters,
      }),
    );
  };

  const generateMutation = useMutation({
    // Mutation callbacks are refreshed in a passive effect. Pass the visible
    // form as variables so a click immediately after restoration cannot use
    // the previous render's draft.
    mutationFn: ({
      input,
    }: {
      input: ReturnType<typeof buildTemplateGenerateInput>;
      silent?: boolean;
      previewOnly?: boolean;
      meta?: {
        baseScenario: string;
        selectedPresetIds: string[];
        appliedPresets: ReturnType<typeof toAppliedPresets>;
      };
    }) => generateTemplate(input),
    onError(error, options) {
      const wasPreparingLaunch = state.deferredLaunchRef.current !== null;
      state.deferredLaunchRef.current = null;
      if (options?.silent && !wasPreparingLaunch) {
        return;
      }
      showToast({
        kind: "error",
        message:
          platformErrorCode(error) === "no_valid_characters"
            ? t("template.validation.charactersRequired")
            : error instanceof Error
              ? error.message
              : t("template.error.generateFallback"),
        title: t("template.error.generateFailed"),
      });
    },
    onSuccess(template, options) {
      if (Array.isArray(template.resolvedCharacters)) {
        applyResolvedCharactersFromGeneration(template.resolvedCharacters);
      }
      if (options?.previewOnly) {
        if (!options?.silent) {
          showToast({ kind: "success", message: template.generationMessage, title: t("template.toast.generated") });
        }
        return;
      }
      const normalized = normalizeTemplateSummary({
        ...template,
        appliedPresets: options.meta?.appliedPresets ?? [],
        baseScenario: options.meta?.baseScenario ?? template.scenario ?? options.input.scenario ?? "",
        scenario: template.scenario || options.input.scenario || "",
        selectedPresetIds: options.meta?.selectedPresetIds ?? [],
      });
      state.restoredSessionBackgroundRef.current = null;
      state.setIsCreating(true);
      state.setSessionDraftActive(true);
      state.setDraft(normalized);
      if (!options?.silent) {
        showToast({ kind: "success", message: template.generationMessage, title: t("template.toast.generated") });
      }
      if (state.deferredLaunchRef.current !== null) {
        state.setLaunchReadyAfterRoleGeneration(state.deferredLaunchRef.current);
        state.deferredLaunchRef.current = null;
      }
    },
  });

  useEffect(() => {
    if (!state.sessionRestored) {
      return;
    }
    if (!state.autoGenerateReadyRef.current) {
      state.autoGenerateReadyRef.current = true;
      return;
    }
    if (state.suppressNextAutoGenerateRef.current) {
      state.suppressNextAutoGenerateRef.current = false;
      return;
    }
    if (generateMutation.isPending) {
      return;
    }
    if (state.selectedCharacters.length === 0) {
      return;
    }
    if (state.selectedCharacters.length > 4 && !state.characterPromptMode) {
      return;
    }
    if (state.fullSystemSyncKey === state.lastAutoGeneratedKeyRef.current) {
      return;
    }
    const nextBase = state.scenarioForSelectedCharacters();
    if (nextBase !== state.baseScenario) {
      state.lastAutoScenarioRef.current = nextBase;
      state.updateDraft({ baseScenario: nextBase });
    }
    if (state.systemManuallyEdited) {
      return;
    }
    const scheduledKey = state.fullSystemSyncKey;
    const presetMeta = {
      appliedPresets: state.appliedPresetsSnapshot,
      baseScenario: nextBase,
      selectedPresetIds: state.effectiveSelectedPresetIds,
    };
    const timer = window.setTimeout(() => {
      state.lastAutoGeneratedKeyRef.current = scheduledKey;
      generateMutation.mutate({
        input: latestGenerationInput.current(nextBase),
        meta: presetMeta,
        silent: true,
      });
    }, 160);
    return () => window.clearTimeout(timer);
  }, [
    state.fullSystemSyncKey,
    state.sessionRestored,
    state.systemManuallyEdited,
    state.selectedCharacters.length,
    state.characterPromptMode,
  ]);

  const savePresetsMutation = useMutation({
    mutationFn: async (library: UserPromptPresetLibrary) => {
      if (!state.presetsSuccess) {
        throw new Error(
          state.presetsError instanceof Error ? state.presetsError.message : t("template.presets.loadFailed"),
        );
      }
      return saveUserPromptPresets(library);
    },
    onSuccess(saved) {
      queryClient.setQueryData(userPromptPresetsQueryKey, saved);
    },
  });

  const handleRegenerateFromDialog = useCallback(
    async (rules: SystemPromptRulesDraft, options: { silent: boolean }): Promise<string | null> => {
      if (!state.selectedBackground) {
        if (!options.silent) {
          showToast({
            kind: "error",
            message: t("template.validation.backgroundRequired"),
            title: t("template.mode.generate"),
          });
        }
        return null;
      }
      if (!state.selectedCharacters.length) {
        if (!options.silent) {
          showToast({
            kind: "error",
            message: t("template.validation.charactersRequired"),
            title: t("template.mode.generate"),
          });
        }
        return null;
      }
      if (state.selectedCharacters.length > 4 && !state.characterPromptMode) {
        if (!options.silent) {
          state.setPrimaryCharacterDialogOpen(true);
        }
        return null;
      }
      const nextBase = state.scenarioForSelectedCharacters();
      if (nextBase !== state.baseScenario) {
        state.lastAutoScenarioRef.current = nextBase;
        state.updateDraft({ baseScenario: nextBase });
      }
      try {
        const result = await generateMutation.mutateAsync({
          input: latestGenerationInput.current(nextBase, rules),
          silent: options.silent,
          previewOnly: true,
        });
        return result.system ?? "";
      } catch {
        return null;
      }
    },
    [
      state.baseScenario,
      state.characterPromptMode,
      state.selectedBackground,
      state.selectedCharacters.length,
      showToast,
      t,
    ],
  );

  const handleConfirmUserPrompt = (commit: UserPromptCommit) => {
    state.setSessionDraftActive(true);
    state.updateDraft({
      appliedPresets: commit.appliedPresets,
      selectedPresetIds: commit.selectedPresetIds,
    });
    state.setUserPromptDialogOpen(false);
  };

  const handleConfirmSystemPrompt = (commit: SystemPromptCommit) => {
    const nextCharKey = templateGenerationKey({
      characters: state.selectedCharacters,
      characterPromptMode: state.characterPromptMode,
      primaryCharacters: state.primaryCharacters,
      mediaSelectionMode: commit.mediaSelectionMode,
      ...state.playerOptions,
    });
    const nextSyncKey = buildSystemSyncKey({
      characterKey: nextCharKey,
      backgroundName: state.selectedBackground,
      voiceLanguage: state.voiceLanguage,
      useCg: state.useCg,
      useEffect: commit.useEffectPrompt,
      useTranslation: commit.useTranslation,
      useCot: commit.useCot,
      useChoice: commit.useChoice,
      useNarration: commit.useNarration,
      useStat: commit.useStat,
      maxSpeechChars: commit.maxSpeechChars,
      maxDialogItems: commit.maxDialogItems,
      outputFormat: commit.outputFormat,
    });

    // Prevent redundant immediate auto-generation after confirming inside dialog.
    state.lastAutoGeneratedKeyRef.current = nextSyncKey;
    if (commit.system !== (state.draft.system ?? "")) {
      state.setSessionDraftActive(true);
    }
    state.setMediaSelectionMode(commit.mediaSelectionMode);
    state.setOutputFormat(commit.outputFormat);
    state.setUseEffectPrompt(commit.useEffectPrompt);
    state.setUseTranslation(commit.useTranslation);
    state.setUseCot(commit.useCot);
    state.setUseChoice(commit.useChoice);
    state.setUseNarration(commit.useNarration);
    state.setUseStat(commit.useStat);
    state.setMaxSpeechChars(commit.maxSpeechChars);
    state.setMaxDialogItems(commit.maxDialogItems);
    state.setSystemManuallyEdited(commit.systemManuallyEdited);
    state.setManualBaseKey(commit.systemManuallyEdited ? nextSyncKey : "");
    state.updateDraft({
      mediaSelectionMode: commit.mediaSelectionMode,
      outputFormat: commit.outputFormat,
      system: commit.system,
    });
    state.setSystemPromptDialogOpen(false);
  };

  return {
    generateMutation,
    generationInput,
    handleConfirmSystemPrompt,
    handleConfirmUserPrompt,
    handleRegenerateFromDialog,
    savePresetsMutation,
  };
}
